-- Join a class by code without exposing all class rows to students.
create or replace function public.join_class_by_code(p_code text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_class public.classes%rowtype;
  v_user text := auth.jwt() ->> 'sub';
  v_role text := auth.jwt() -> 'metadata' ->> 'role';
begin
  if v_user is null or v_role <> 'student' then
    raise exception 'Only students can join a class';
  end if;

  select * into v_class
  from public.classes
  where upper(join_code) = upper(trim(p_code))
    and archived = false
  limit 1;

  if v_class.id is null then
    raise exception 'Class code not found';
  end if;

  insert into public.class_members(class_id, student_id, teacher_id)
  values (v_class.id, v_user, v_class.teacher_id)
  on conflict (class_id, student_id) do nothing;

  return v_class.id;
end;
$$;

grant execute on function public.join_class_by_code(text) to authenticated;

-- Teacher adds a student using the student's profile code.
create or replace function public.teacher_add_student_by_code(p_class_id bigint, p_student_code text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_teacher text := auth.jwt() ->> 'sub';
  v_role text := auth.jwt() -> 'metadata' ->> 'role';
  v_student text;
begin
  if v_teacher is null or v_role <> 'teacher' then
    raise exception 'Only teachers can add students';
  end if;

  if not exists (select 1 from public.classes where id = p_class_id and teacher_id = v_teacher) then
    raise exception 'Class not found';
  end if;

  select id into v_student
  from public.profiles
  where role = 'student' and student_id = trim(p_student_code)
  limit 1;

  if v_student is null then
    raise exception 'Student code not found';
  end if;

  insert into public.class_members(class_id, student_id, teacher_id)
  values (p_class_id, v_student, v_teacher)
  on conflict (class_id, student_id) do nothing;

  return v_student;
end;
$$;

grant execute on function public.teacher_add_student_by_code(bigint, text) to authenticated;

-- Automatically capture submission revisions.
create or replace function public.capture_submission_revision()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'submitted' and new.submitted_at is not null
     and (tg_op = 'INSERT' or old.submitted_at is distinct from new.submitted_at) then
    insert into public.submission_revisions(submission_id, student_id, content, file_path, submitted_at)
    values (new.id, new.student_id, new.content, new.file_path, new.submitted_at);
  end if;
  return new;
end;
$$;

drop trigger if exists capture_submission_revision_trigger on public.submissions;
create trigger capture_submission_revision_trigger
after insert or update on public.submissions
for each row execute function public.capture_submission_revision();

