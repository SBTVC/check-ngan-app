-- Notification helpers and triggers.
create or replace function public.notify_new_assignment()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.class_id is not null then
    insert into public.notifications(user_id, title, message, href)
    select cm.student_id, 'มีงานใหม่', new.title, '/student/assignments/' || new.id
    from public.class_members cm
    where cm.class_id = new.class_id;
  end if;
  return new;
end;
$$;

drop trigger if exists notify_new_assignment_trigger on public.assignments;
create trigger notify_new_assignment_trigger
after insert on public.assignments
for each row execute function public.notify_new_assignment();

create or replace function public.notify_new_submission()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_teacher text;
  v_title text;
begin
  if new.status = 'submitted' and new.submitted_at is not null
     and (tg_op = 'INSERT' or old.submitted_at is distinct from new.submitted_at) then
    select a.teacher_id, a.title into v_teacher, v_title
    from public.assignments a where a.id = new.assignment_id;
    if v_teacher is not null then
      insert into public.notifications(user_id, title, message, href)
      values (v_teacher, 'มีนักเรียนส่งงาน', coalesce(v_title, 'งานที่มอบหมาย'), '/teacher/submissions/' || new.id);
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists notify_new_submission_trigger on public.submissions;
create trigger notify_new_submission_trigger
after insert or update on public.submissions
for each row execute function public.notify_new_submission();

create or replace function public.notify_grade_saved()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_student text;
  v_assignment bigint;
  v_title text;
begin
  select s.student_id, s.assignment_id into v_student, v_assignment
  from public.submissions s where s.id = new.submission_id;
  select title into v_title from public.assignments where id = v_assignment;
  if v_student is not null then
    insert into public.notifications(user_id, title, message, href)
    values (v_student, 'ตรวจงานแล้ว', coalesce(v_title, 'งานที่ส่ง'), '/student/assignments/' || v_assignment);
  end if;
  return new;
end;
$$;

drop trigger if exists notify_grade_saved_trigger on public.grades;
create trigger notify_grade_saved_trigger
after insert or update on public.grades
for each row execute function public.notify_grade_saved();

