-- Profiles: users manage themselves. Teachers may read students in their classes
-- or students who submitted to their assignments. Students may read teachers of joined classes.
drop policy if exists teachers_read_related_student_profiles on public.profiles;
create policy teachers_read_related_student_profiles
on public.profiles for select to authenticated
using (
  (select auth.jwt() -> 'metadata' ->> 'role') = 'teacher'
  and role = 'student'
  and (
    exists (
      select 1 from public.class_members cm
      where cm.student_id = profiles.id
        and cm.teacher_id = (select auth.jwt() ->> 'sub')
    )
    or exists (
      select 1
      from public.submissions s
      join public.assignments a on a.id = s.assignment_id
      where s.student_id = profiles.id
        and a.teacher_id = (select auth.jwt() ->> 'sub')
    )
  )
);

drop policy if exists students_read_joined_teacher_profiles on public.profiles;
create policy students_read_joined_teacher_profiles
on public.profiles for select to authenticated
using (
  (select auth.jwt() -> 'metadata' ->> 'role') = 'student'
  and role = 'teacher'
  and exists (
    select 1 from public.class_members cm
    where cm.student_id = (select auth.jwt() ->> 'sub')
      and cm.teacher_id = profiles.id
  )
);

