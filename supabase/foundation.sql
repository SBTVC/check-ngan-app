-- Profiles: a user manages only their own profile, and profile role must match JWT.
drop policy if exists profiles_select_self on public.profiles;
create policy profiles_select_self
on public.profiles for select to authenticated
using (id = (select auth.jwt() ->> 'sub'));

drop policy if exists profiles_insert_self on public.profiles;
create policy profiles_insert_self
on public.profiles for insert to authenticated
with check (
  id = (select auth.jwt() ->> 'sub')
  and role = (select auth.jwt() -> 'metadata' ->> 'role')
);

drop policy if exists profiles_update_self on public.profiles;
create policy profiles_update_self
on public.profiles for update to authenticated
using (id = (select auth.jwt() ->> 'sub'))
with check (
  id = (select auth.jwt() ->> 'sub')
  and role = (select auth.jwt() -> 'metadata' ->> 'role')
);

-- Classes: teacher manages own classes; student reads joined classes.
drop policy if exists teachers_manage_own_classes on public.classes;
create policy teachers_manage_own_classes
on public.classes for all to authenticated
using (
  teacher_id = (select auth.jwt() ->> 'sub')
  and (select auth.jwt() -> 'metadata' ->> 'role') = 'teacher'
)
with check (
  teacher_id = (select auth.jwt() ->> 'sub')
  and (select auth.jwt() -> 'metadata' ->> 'role') = 'teacher'
);

drop policy if exists students_read_joined_classes on public.classes;
create policy students_read_joined_classes
on public.classes for select to authenticated
using (
  (select auth.jwt() -> 'metadata' ->> 'role') = 'student'
  and exists (
    select 1
    from public.class_members cm
    where cm.class_id = classes.id
      and cm.student_id = (select auth.jwt() ->> 'sub')
  )
);

