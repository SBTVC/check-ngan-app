-- ---------------------------------------------------------------------------
-- Existing tables: normalize Clerk user IDs and add application columns.
-- ---------------------------------------------------------------------------

alter table public.profiles enable row level security;

-- Clerk user IDs are strings such as user_xxx, not UUIDs.
alter table public.assignments
  alter column teacher_id type text using teacher_id::text;

alter table public.assignments
  add column if not exists class_id bigint,
  add column if not exists max_score numeric not null default 100 check (max_score >= 0),
  add column if not exists file_path text,
  add column if not exists updated_at timestamptz not null default now();

alter table public.submissions
  add column if not exists content text,
  add column if not exists file_path text,
  add column if not exists submitted_at timestamptz,
  add column if not exists updated_at timestamptz not null default now();

-- Preserve legacy submission text.
update public.submissions
set content = detail
where content is null and detail is not null;

-- ---------------------------------------------------------------------------
-- Core classroom tables.
-- ---------------------------------------------------------------------------

create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  name text not null,
  subject text,
  teacher_id text not null default (auth.jwt() ->> 'sub'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Needed for composite foreign keys that guarantee the teacher owns the class.
alter table public.classes
  drop constraint if exists classes_id_teacher_id_key;

alter table public.classes
  add constraint classes_id_teacher_id_key unique (id, teacher_id);

create table if not exists public.class_members (
  class_id bigint not null,
  student_id text not null,
  teacher_id text,
  joined_at timestamptz not null default now(),
  primary key (class_id, student_id)
);

-- Backfill teacher_id safely if this migration is re-run after memberships exist.
update public.class_members cm
set teacher_id = c.teacher_id
from public.classes c
where c.id = cm.class_id
  and cm.teacher_id is null;

alter table public.class_members
  alter column teacher_id set not null;

alter table public.class_members
  drop constraint if exists class_members_class_id_fkey,
  drop constraint if exists class_members_class_teacher_fkey;

alter table public.class_members
  add constraint class_members_class_teacher_fkey
  foreign key (class_id, teacher_id)
  references public.classes(id, teacher_id)
  on delete cascade;

-- Assignment must point to a class owned by the same teacher.
alter table public.assignments
  drop constraint if exists assignments_class_id_fkey,
  drop constraint if exists assignments_class_teacher_fkey;

alter table public.assignments
  add constraint assignments_class_teacher_fkey
  foreign key (class_id, teacher_id)
  references public.classes(id, teacher_id)
  on delete cascade;

-- One student has one submission row per assignment. Re-submission updates that row.
alter table public.submissions
  drop constraint if exists submissions_assignment_student_key;

alter table public.submissions
  add constraint submissions_assignment_student_key
  unique (assignment_id, student_id);

create table if not exists public.grades (
  submission_id bigint primary key references public.submissions(id) on delete cascade,
  score numeric not null check (score >= 0),
  feedback text,
  graded_by text default (auth.jwt() ->> 'sub'),
  graded_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Preserve legacy score/feedback before grading moves fully to public.grades.
insert into public.grades (submission_id, score, feedback, graded_by, graded_at)
select id, score, feedback, null, coalesce(created_at, now())
from public.submissions
where score is not null
on conflict (submission_id) do nothing;

-- Enforce score <= assignment.max_score at the database layer.
create or replace function public.validate_grade_score()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  assignment_max_score numeric;
begin
  select a.max_score
    into assignment_max_score
  from public.submissions s
  join public.assignments a on a.id = s.assignment_id
  where s.id = new.submission_id;

  if assignment_max_score is null then
    raise exception 'Assignment not found for submission %', new.submission_id;
  end if;

  if new.score < 0 or new.score > assignment_max_score then
    raise exception 'Score must be between 0 and %', assignment_max_score;
  end if;

  return new;
end;
$$;

drop trigger if exists validate_grade_score_trigger on public.grades;
create trigger validate_grade_score_trigger
before insert or update on public.grades
for each row execute function public.validate_grade_score();

